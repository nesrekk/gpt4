"""Shared helpers for the medical symptom assistant.

The lab sheet says GPT-4; the lab runs offline with Ollama (Llama 3.2) as the local stand-in.
"""
import json
import os

import ollama

MODEL = "llama3.2"
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
REPORT_DIR = os.path.join(BASE_DIR, "reports")

DISCLAIMER = ("This is general health information generated by an AI model, NOT a medical "
              "diagnosis. Always consult a qualified doctor. In an emergency call 108 (India) "
              "or go to the nearest hospital immediately.")

SYSTEM = ("You are a cautious medical information assistant. You never give a definite "
          "diagnosis, never prescribe prescription drugs or doses, always mention uncertainty, "
          "and always recommend seeing a qualified doctor when symptoms are serious, severe or "
          "persistent.")

client = ollama.Client()


def ask_llm_json(prompt, temperature=0.2):
    """Ask Ollama for a JSON answer (format='json') and parse it.

    In JSON mode a small model occasionally keeps generating whitespace forever, so the
    answer length is capped and a cut-off / invalid answer is retried at a higher temperature.
    """
    for attempt in range(3):
        response = client.chat(
            model=MODEL,
            messages=[{"role": "system", "content": SYSTEM}, {"role": "user", "content": prompt}],
            format="json",
            options={"temperature": temperature, "num_predict": 1500},
        )
        try:
            return json.loads(response["message"]["content"])
        except json.JSONDecodeError:
            temperature = min(temperature + 0.3, 1.0)
    raise RuntimeError("The model did not return valid JSON after 3 attempts.")


def heading(title, width=62):
    print("\n" + title)
    print("-" * width)
